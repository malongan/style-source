def lookup(style_id: str, category: str, kv_var: str):
    """查表，优先级：按风格 > 按分类 > 通用。返回 (desc, 来源) 或 (None, None)。"""
    slot = BY_STYLE.get(style_id) or {}
    if kv_var in slot:
        return slot[kv_var], 'style:%s' % style_id
    slot = BY_CATEGORY.get(category) or {}
    if kv_var in slot:
        return slot[kv_var], category
    if kv_var in COMMON:
        return COMMON[kv_var], 'common'
    return None, None


