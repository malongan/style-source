def fill_file(path: str, apply: bool, refresh: bool = False):
    """处理单个文件。返回 (改动列表, 未覆盖列表)。

    refresh=True 时额外做一件事：把"当前 desc 恰好等于该槽位走 COMMON/BY_CATEGORY
    会得到的值"的条目，按 BY_STYLE 重写。这是为了避免上一轮按名字批量补的
    通用 desc 留在主题完全不同的风格里。只覆盖机器写的值，人工写的值动不到。
    """
    category = os.path.basename(os.path.dirname(path))
    text = open(path, encoding='utf-8').read()
    data = yaml.safe_load(text) or {}
    style_id = str(data.get('id') or '')
    variables = data.get('variables') or []
    if not isinstance(variables, list):
        return [], []

    changed, uncovered = [], []
    for item in variables:
        if not isinstance(item, dict):
            continue
        kv = str(item.get('kv_var') or '').strip()
        if not kv:
            continue
        existing = str(item.get('desc') or '').strip()
        if existing:
            if refresh:
                # 一、该风格有专属词条：机器写的通用值（含已废弃的旧值）换成专属值
                by_style = BY_STYLE.get(style_id) or {}
                if kv in by_style:
                    machine, _ = lookup('', category, kv)     # 跳过 BY_STYLE 层
                    machine_written = existing == machine or existing in LEGACY_DESC
                    if machine_written and existing != by_style[kv]:
                        changed.append((kv, by_style[kv], 'style-refresh'))
                        continue
                # 二、上一轮通用词表写的、现已判定与部分风格错配的值
                legacy = LEGACY_DESC.get(existing)
                if legacy and legacy != existing:
                    changed.append((kv, legacy, 'legacy-refresh'))
            continue                      # 幂等：已有 desc 的一律不动
        if kv in SKIP:
            continue                      # 结构槽位，不该补 desc
        desc, src = lookup(style_id, category, kv)
        if not desc:
            uncovered.append(kv)
            continue
        if not (MIN_LEN <= len(desc) <= MAX_LEN):
            uncovered.append(kv)
            continue
        changed.append((kv, desc, src))

    if not (apply and changed):
        return changed, uncovered

    # 文本级改写：定位每个 kv_var 的条目范围，块内已有 desc 就替换，没有就插在
    # style_var 后面。绝不整段重排，避免产生无关 diff。
    lines = text.split('\n')
    heads = []
    for idx, line in enumerate(lines):
        m = ENTRY_RE.match(line)
        if m:
            heads.append((idx, m.group(2).strip().strip('"\'')))

    ranges = {}
    for k, (start, kv) in enumerate(heads):
        end = heads[k + 1][0] if k + 1 < len(heads) else len(lines)
        ranges.setdefault(kv, (start, end))

    replace_at, insert_after = {}, {}
    for kv, desc, _ in changed:
        if kv not in ranges:
            continue
        start, end = ranges[kv]
        desc_line = style_line = None
        for j in range(start + 1, end):
            if re.match(r'^\s+desc:', lines[j]):
                desc_line = j
            elif re.match(r'^\s+style_var:', lines[j]):
                style_line = j
        anchor = desc_line if desc_line is not None else style_line
        if anchor is None:
            continue                       # 结构不对，不硬插，留给人工
        indent = re.match(r'^(\s+)', lines[anchor]).group(1)
        new_line = '%sdesc: %s' % (indent, desc)
        if desc_line is not None:
            replace_at[desc_line] = new_line
        else:
            insert_after[style_line] = new_line

    out = []
    for i, line in enumerate(lines):
        out.append(replace_at.get(i, line))
        if i in insert_after:
            out.append(insert_after[i])
    new_text = '\n'.join(out)

    # 写回前再验一次：解析结果必须与原文件除 desc 外完全一致
    try:
        after = yaml.safe_load(new_text) or {}
    except Exception as exc:
        print('  !! %s 写入后会破坏 YAML（%s），已跳过' % (path, exc))
        return [], uncovered
    if [v.get('kv_var') for v in after.get('variables', [])] != \
            [v.get('kv_var') for v in variables]:
        print('  !! %s 变量顺序会变，已跳过' % path)
        return [], uncovered

    open(path, 'w', encoding='utf-8').write(new_text)
    return changed, uncovered


def main():
    ap = argparse.ArgumentParser(description='为缺少 desc 的变量补写填写提示')
    ap.add_argument('--apply', action='store_true', help='写回文件（默认干跑）')
    ap.add_argument('--category', help='只处理某个分类目录')
    ap.add_argument('--uncovered', action='store_true', help='只输出词表没覆盖的变量名')
    ap.add_argument('--refresh', action='store_true',
                    help='把 BY_STYLE 里的风格，其机器写的通用 desc 按风格重写（人工值不动）')
    args = ap.parse_args()

    files = sorted(glob.glob(STYLE_GLOB))
    if args.category:
        files = [f for f in files if '/%s/' % args.category in f]

    total_changed = total_uncovered = files_touched = 0
    uncovered_names = {}

    for path in files:
        changed, uncovered = fill_file(path, args.apply, refresh=args.refresh)
        if changed:
            files_touched += 1
            total_changed += len(changed)
            if not args.uncovered:
                print('%s  (+%d)' % (os.path.relpath(path, ROOT), len(changed)))
                for kv, desc, src in changed:
                    print('    %-12s %s' % (kv, desc))
        for kv in uncovered:
            uncovered_names.setdefault(kv, 0)
            uncovered_names[kv] += 1
            total_uncovered += 1

    print()
    mode = '已写回' if args.apply else 'DRY-RUN'
    print('%s：%d 个文件 / %d 条 desc' % (mode, files_touched, total_changed))
    if total_uncovered:
        print('词表未覆盖：%d 条 / %d 种变量名（需要人工写）' % (total_uncovered, len(uncovered_names)))
        for kv, n in sorted(uncovered_names.items(), key=lambda x: -x[1])[:40]:
            print('    %-22s %d' % (kv, n))
    return 0


if __name__ == '__main__':
    sys.exit(main())
